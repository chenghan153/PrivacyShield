#!/usr/bin/env python3
"""Write a reproducible synthetic evaluation and five-document benchmark."""

from __future__ import annotations

import json
import statistics
import time
from io import BytesIO
from pathlib import Path

from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

from privacyshield.evaluation import run_synthetic_evaluation
from privacyshield.pipeline import analyze, export


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "evaluation"
CUSTOM = {"internal_project": ["Project ORION"], "client_name": ["ACME HEALTH"]}


def make_pdf(index: int) -> bytes:
    values = [
        ("alex@example.com", "+886 912-345-678", "75,000"),
        ("river@example.org", "+1 415-555-0132", "18,500"),
        ("dev.team@example.dev", "02-2345-6789", "220,000"),
        ("owner@example.net", "+44 20-7946-0958", "43,200"),
        ("qa@example.io", "0912-111-222", "9,750"),
    ]
    email, phone, budget = values[index]
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=letter)
    lines = [
        "Client: ACME HEALTH",
        "Internal project: Project ORION",
        f"Email: {email}",
        f"Phone: {phone}",
        f"API key: sk_test_DEMOONLY{index}987654321",
        f"Budget: USD {budget}",
    ]
    for row, line in enumerate(lines):
        pdf.drawString(72, 720 - row * 36, line)
    pdf.save()
    return buffer.getvalue()


def main() -> None:
    OUT.mkdir(exist_ok=True)
    detector = run_synthetic_evaluation()
    timings: list[float] = []
    counts: list[int] = []
    for index in range(5):
        data = make_pdf(index)
        started = time.perf_counter()
        document, findings = analyze(data, f"synthetic_{index + 1}.pdf", "Public", CUSTOM)
        export(document, findings)
        timings.append((time.perf_counter() - started) * 1000)
        counts.append(len(findings))
    benchmark = {
        "documents": 5,
        "document_type": "in-memory synthetic one-page text PDFs",
        "audience": "Public",
        "mean_ms": round(statistics.mean(timings), 2),
        "median_ms": round(statistics.median(timings), 2),
        "min_ms": round(min(timings), 2),
        "max_ms": round(max(timings), 2),
        "findings_per_document": counts,
        "manual_baseline": "not measured",
    }
    result = {"detector": detector, "benchmark": benchmark}
    (OUT / "results.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    report = f"""# Synthetic evaluation report

Generated by `python scripts/evaluate.py` on 2026-10-11.

## Detector fixture results

- Cases: **{detector['cases']}** ({detector['positive_labels']} expected positive labels; includes 3 explicit negative/ambiguous cases)
- TP / FP / FN: **{detector['tp']} / {detector['fp']} / {detector['fn']}**
- Precision / recall: **{detector['precision']:.1%} / {detector['recall']:.1%}**
- Scope: {detector['scope']}.

This fixture result checks known deterministic patterns. It is not evidence of production accuracy, OCR robustness, or performance on real corporate documents.

## Five-document system benchmark

- Inputs: {benchmark['documents']} {benchmark['document_type']}
- Full local analyze + Public-policy raster export: median **{benchmark['median_ms']:.2f} ms/document** (range {benchmark['min_ms']:.2f}–{benchmark['max_ms']:.2f} ms)
- Findings per document: {', '.join(str(value) for value in counts)}
- Hardware-specific measurement; warm/cold cache and document complexity affect results.
- Human/manual redaction time: **not measured**. Any ROI shown in the proposal is an adjustable scenario, not a validated savings claim.

## Known gaps

- The text-fragment fixtures bypass OCR; OCR errors are separately mitigated by visible preview and mandatory human review.
- The sample set is synthetic and intentionally aligned with supported regex/dictionary patterns.
- Phone formats, handwritten content, tables, rotated scans, and unknown secret formats require broader validation.
"""
    (OUT / "REPORT.md").write_text(report, encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
